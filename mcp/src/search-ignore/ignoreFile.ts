import { stripBom } from "./p4ignore";

export const OWNER_PREFIX = "# generated by /dev-workflow:search-ignore";

export function isOwned(text: string): boolean {
  const first = stripBom(text).split(/\r?\n/)[0] ?? "";
  return first.startsWith(OWNER_PREFIX);
}

export function renderIgnore(sourceName: string, system: string[], user: string[]): string {
  const head = [
    `${OWNER_PREFIX} — do not edit`,
    "# 직접 고치면 다음 실행 때 사라집니다. .claude/ignore.yaml의 user 부분을 고친 뒤 /dev-workflow:search-ignore를 다시 실행하세요",
    `# source: ${sourceName}`,
  ];
  const seen = new Set(system);
  const extra: string[] = [];
  for (const u of user) {
    if (!seen.has(u)) {
      seen.add(u);
      extra.push(u);
    }
  }
  return [...head, ...system, ...extra, ""].join("\n");
}
